"""E2E commentaire seul : écran admin (helpers réels) -> supabase-js -> PostgREST -> PostgreSQL JETABLE -> écran candidat.

Définitions de production relevées le 10/11 (fixtures eb3-20261110) + correctif commentaire seul, RLS de lecture
copiée de la production. Aucune connexion au projet réel. Usage : python3 src/test/qrc_commentaire_http_e2e.py
"""
import base64, hashlib, hmac, json, os, pathlib, subprocess, threading, time, unittest, uuid
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from urllib.request import Request, urlopen
from urllib.error import HTTPError
import eb3_correction_v2_contract as eb3
from upsert_reponse_http_integration import PgJetable, port_libre, attendre_http

ROOT = pathlib.Path(__file__).resolve().parents[2]
SECRET = "integration-locale-32-caracteres-minimum"
ADMIN, ELEVE, AUTRE = eb3.ADMIN, eb3.ELEVE_UID, eb3.AUTRE_UID


def jwt(sub=None, role="authenticated"):
    b = lambda v: base64.urlsafe_b64encode(v).rstrip(b"=").decode()
    h = b(json.dumps({"alg": "HS256", "typ": "JWT"}).encode())
    p = {"role": role, "iat": 1, "exp": 4_000_000_000, **({"sub": sub, "aud": "authenticated"} if sub else {})}
    body = b(json.dumps(p).encode())
    return f"{h}.{body}.{b(hmac.new(SECRET.encode(), f'{h}.{body}'.encode(), hashlib.sha256).digest())}"


class E2E(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.pg = pg = PgJetable()
        assert pg.dir.startswith("/tmp/") and pg.port != 5432
        com = (ROOT / "docs/sql-revue/2026-11-10-qrc-commentaire-seul.sql").read_text().split("CREATE OR REPLACE FUNCTION public.qrc_historique_commenter")[0]
        for part in (eb3.PRELUDE, (eb3.FIX / "schema_live.sql").read_text(), eb3.POST, (eb3.FIX / "fonctions_live.sql").read_text(), eb3.TRIGGERS,
                     "REVOKE EXECUTE ON ALL FUNCTIONS IN SCHEMA public FROM PUBLIC;", (eb3.FIX / "droits_live.sql").read_text().replace("FUNCTION core_", "FUNCTION public.core_"),
                     "CREATE TABLE IF NOT EXISTS public.qrc_bareme_restaure (qrc_instance_id uuid PRIMARY KEY, bareme numeric NOT NULL CHECK (bareme > 0));",
                     (ROOT / "docs/sql-revue/2026-11-10-qrc-v2-bareme-garde.sql").read_text(),
                     "ALTER TABLE public.qrc_correction_events ALTER COLUMN correction_event_id SET NOT NULL; ALTER TABLE public.qrc_correction_events ALTER COLUMN correction_event_id ADD GENERATED BY DEFAULT AS IDENTITY; ALTER TABLE public.qrc_correction_events ADD PRIMARY KEY (correction_event_id);",
                     com,
                     # Lecture comme en production : RLS propriétaire ou admin.
                     "GRANT SELECT ON public.qrc_correction_events, public.qrc_instances_v2 TO authenticated;"
                     "ALTER TABLE public.qrc_correction_events ENABLE ROW LEVEL SECURITY; ALTER TABLE public.qrc_instances_v2 ENABLE ROW LEVEL SECURITY;"
                     "CREATE POLICY lecture ON public.qrc_correction_events FOR SELECT TO authenticated USING (public.core_est_proprietaire(apprenant_id) OR public.has_role(auth.uid(),'admin'));"
                     "CREATE POLICY lecture ON public.qrc_instances_v2 FOR SELECT TO authenticated USING (public.core_est_proprietaire(apprenant_id) OR public.has_role(auth.uid(),'admin'));"
                     "ALTER ROLE authenticator LOGIN;"):
            pg.sql(part)
        cls.rest_port, cls.proxy_port = port_libre(), port_libre()
        env = dict(os.environ, PGRST_DB_URI=f"postgresql://authenticator@127.0.0.1:{pg.port}/postgres?sslmode=disable", PGRST_DB_SCHEMAS="public",
                   PGRST_DB_ANON_ROLE="anon", PGRST_JWT_SECRET=SECRET, PGRST_SERVER_HOST="127.0.0.1", PGRST_SERVER_PORT=str(cls.rest_port))
        cls.log = open(pg.dir + "/postgrest.log", "w")
        cls.rest = subprocess.Popen(["nix", "run", "nixpkgs#postgrest", "--"], env=env, stdout=cls.log, stderr=subprocess.STDOUT)
        attendre_http(cls.rest_port, timeout=120)
        fin = time.time() + 60
        while True:
            try:
                with urlopen(Request(f"http://127.0.0.1:{cls.rest_port}/qrc_instances_v2?select=qrc_instance_id&limit=1", headers={"Authorization": f"Bearer {jwt(ADMIN)}"}), timeout=2) as r:
                    if r.status == 200: break
            except Exception:
                if time.time() > fin: raise
                time.sleep(0.3)
        port = cls.rest_port

        class Proxy(BaseHTTPRequestHandler):
            def log_message(self, *_): pass
            def _f(self):
                n = int(self.headers.get("Content-Length", "0")); body = self.rfile.read(n) if n else None
                hd = {k: v for k, v in self.headers.items() if k.lower() not in ("host", "content-length", "connection")}
                path = self.path[len("/rest/v1"):] if self.path.startswith("/rest/v1") else self.path
                try: res = urlopen(Request(f"http://127.0.0.1:{port}{path}", data=body, headers=hd, method=self.command))
                except HTTPError as e: res = e
                data = res.read(); self.send_response(res.status)
                for k, v in res.headers.items():
                    if k.lower() not in ("connection", "content-length", "transfer-encoding"): self.send_header(k, v)
                self.send_header("Content-Length", str(len(data))); self.end_headers(); self.wfile.write(data)
            do_GET = do_POST = do_PATCH = do_HEAD = _f
        cls.proxy = ThreadingHTTPServer(("127.0.0.1", cls.proxy_port), Proxy)
        threading.Thread(target=cls.proxy.serve_forever, daemon=True).start()

    @classmethod
    def tearDownClass(cls):
        cls.rest.terminate(); cls.proxy.shutdown(); cls.log.close(); cls.pg.stop()

    def client(self, uid, action, arg, role="authenticated"):
        env = dict(os.environ, E2E_URL=f"http://127.0.0.1:{self.proxy_port}", E2E_TOKEN=jwt(uid, role))
        r = subprocess.run(["bun", "run", str(ROOT / "src/test/qrc_commentaire_e2e_client.ts"), action, json.dumps(arg)], capture_output=True, text=True, env=env, cwd=ROOT, timeout=60)
        return json.loads(r.stdout.strip().splitlines()[-1])

    def preparer(self, snap_file):
        snap = json.loads((eb3.FIX / snap_file).read_text())
        att = str(uuid.uuid4()); qrcs = []
        self.pg.sql(f"INSERT INTO public.exam_attempts_v2 (attempt_id, apprenant_id, exam_id, snapshot, etat) VALUES ('{att}','{eb3.APP}',{eb3.lit(snap['exam_id'])},{eb3.lit(json.dumps(snap, ensure_ascii=False))}::jsonb,'en_cours')")
        for q in snap["questions"]:
            if q["type"] == "QRC":
                qi = str(uuid.uuid4()); qrcs.append((qi, q["points"]))
                self.pg.sql(f"INSERT INTO public.qrc_instances_v2 (qrc_instance_id, attempt_id, question_id, apprenant_id, reponse) VALUES ('{qi}','{att}',{eb3.lit(q['id'])},'{eb3.APP}','\"réponse fictive\"'::jsonb)")
        self.pg.sql(f"UPDATE public.exam_attempts_v2 SET etat='terminee', finished_at=now() WHERE attempt_id='{att}'")
        return att, qrcs

    def empreinte(self, att):
        return self.pg.sql(f"SELECT md5(string_agg(qrc_instance_id||etat||coalesce(note::text,'')||coalesce(corrige_at::text,'')||reponse::text, ',' ORDER BY qrc_instance_id)) || coalesce((SELECT md5(r::text) FROM public.core_exam_results r WHERE attempt_id='{att}'),'') FROM public.qrc_instances_v2 WHERE attempt_id='{att}'")

    def _parcours(self, snap_file):
        att, qrcs = self.preparer(snap_file)
        (qi, pts), (qi2, pts2) = qrcs[0], qrcs[1]
        self.assertIsNone(self.client(ADMIN, "corriger", {"qi": qi, "note": pts / 2})["erreur"])
        self.assertIsNone(self.client(ADMIN, "corriger", {"qi": qi2, "note": pts2})["erreur"])
        avant = self.empreinte(att)
        # 1er envoi : deux boutons cumulés, double clic simultané = une seule écriture.
        r = self.client(ADMIN, "commenter", {"qi": qi, "note": pts / 2, "boutons": [0, 1]})
        self.assertEqual(r["erreurs"], [None, None], r); self.assertTrue(r["confirme"], r); self.assertEqual(r["nb"], 2, r)
        self.assertEqual(sorted(map(str, r["rejeux"])), ["False", "True"])
        # 2e envoi : boutons restants + texte libre, sur la version relue.
        r2 = self.client(ADMIN, "commenter", {"qi": qi, "note": pts / 2, "boutons": [2, 3, 0], "libre": "\nRevoir le cours"})
        attendu = "Précisez !!!\nMal dit !!!\nPrécisez permis de conduire hors période probatoire\nAttention aux fautes !!!\nRevoir le cours"
        self.assertEqual(r2["texte"], attendu); self.assertTrue(r2["confirme"], r2); self.assertEqual(r2["nb"], 3)
        # Version périmée (autre onglet) refusée.
        self.assertIn("COMMENTAIRE_CONFLIT", self.client(ADMIN, "perime", {"qi": qi, "note": pts / 2, "ev": 1})["erreur"] or "")
        # Candidat après rechargement : dernière version, sous RLS ; QRC sans commentaire = rien.
        c = self.client(ELEVE, "candidat", {"att": att})
        self.assertEqual(c["commentaires"][qi], attendu); self.assertIsNone(c["commentaires"][qi2]); self.assertEqual(c["nbQrc"], len(qrcs))
        # Autre élève : ne voit rien ; élève et anonyme ne peuvent pas commenter.
        self.assertEqual(self.client(AUTRE, "candidat", {"att": att}), {"nbQrc": 0, "nbEvents": 0, "commentaires": {}})
        self.assertIsNotNone(self.client(ELEVE, "perime", {"qi": qi, "note": pts / 2, "ev": 3})["erreur"])
        self.assertIsNotNone(self.client(None, "perime", {"qi": qi, "note": pts / 2, "ev": 3}, role="anon")["erreur"])
        # Notes, état, réponses et résultat inchangés par les commentaires.
        self.assertEqual(avant, self.empreinte(att))

    def test_vtc_admin_api_candidat(self):
        self._parcours("snap_eb3_vtc_gestion.json")

    def test_taxi_admin_api_candidat(self):
        self._parcours("snap_eb3_taxi.json")


if __name__ == "__main__":
    unittest.main(verbosity=2)
